C******************************************************************************C
C******************************************************************************C
C***       This routine transposes two planes of the res matrix             ***C
C******************************************************************************C
C******************************************************************************C

        subroutine xyTxz_wait

        include 'appbt.incl'

C******************************************************************************C
C******************************************************************************C
c***  restore the message buffer.
           
        do 210 icount = 1, ndcolm1
           
           jrc = ndrec_col(icount)
           
           call msgwait (msidrec(icount))
           
           do 220 i = 1, nx
              
              u(i,jrc,1) = bufrec(i,1,jrc)
              u(i,jrc,2) = bufrec(i,2,jrc)
              u(i,jrc,3) = bufrec(i,3,jrc)
              u(i,jrc,4) = bufrec(i,4,jrc)
              u(i,jrc,5) = bufrec(i,5,jrc)
              
 220       continue
              
 210    continue

        return 

        end

