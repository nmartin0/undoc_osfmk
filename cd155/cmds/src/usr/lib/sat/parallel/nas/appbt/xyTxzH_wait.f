        subroutine xyTxzH_wait

        include 'appbt.incl'

C******************************************************************************C
C******************************************************************************C
c***  restore the message buffer.
           
        do 210 icount = 1, ndcolm1
           
           jrc = ndrec_col(icount)
           
           call msgwait (msidrec(icount))
           
           do 220 i = 1, nxnriv

              temp(1,jrc,i) = bufrow(i,1,jrc)
              temp(2,jrc,i) = bufrow(i,2,jrc)
              temp(3,jrc,i) = bufrow(i,3,jrc)
              temp(4,jrc,i) = bufrow(i,4,jrc)
              temp(5,jrc,i) = bufrow(i,5,jrc)
              
 220       continue
              
 210    continue

        return 

        end

