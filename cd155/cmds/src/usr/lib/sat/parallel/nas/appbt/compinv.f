        subroutine compinv (iimin,iimax,jjmin,jjmax)

        include 'appbt.incl'

C******************************************************************************C
C******************************************************************************C

        if ((my_col.gt.1).and.(my_col.lt.node_col)) then
           
           do 100 j = jjmin, jjmax
              do 200 i = iimin, iimax
                 
                 uiv(i,j) = 1.d0/u(i,j,1)
                 
                 qu(i,j) = 0.5d0*uiv(i,j)*(u(i,j,2)*u(i,j,2)+
     &                u(i,j,3)*u(i,j,3)+u(i,j,4)*u(i,j,4))
                 
 200          continue
 100       continue
           
        elseif ((my_col.eq.1).or.(my_col.eq.node_col)) then
           
           do 300 j = 1, ny
              do 400 i = 1, nx
                 
                 uiv(i,j) = 1.d0/u(i,j,1)
                 
 400          continue
 300       continue
           
        endif

        return

        end

