char	*malloc();

/*
 * NAME: valloc
 * FUNCTION:  allocates size bytes aligned on a page boundary.
 */
char *
valloc(i)
	int i;
{
	int valsiz = getpagesize(), j;
	char *cp = malloc(i + (valsiz-1));

	j = ((int)cp + (valsiz-1)) &~ (valsiz-1);
	return ((char *)j);
}
