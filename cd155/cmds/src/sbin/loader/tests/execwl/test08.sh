PATH=:$PATH

testpurpose="test that good filename is actually passed to the loader"

status="STATUS($0:$$)"
error="ERROR($0:$$)"

while [ "$1" != "" ]
do
    case $1 in
    -v)		vflag=1;;
    esac
    shift
done

if [ "$vflag" = 1 ]
then
    echo "$status: $testpurpose"
fi

if [ "`exec_with_loader 0 print_file_loader /bin/ls`" = "/bin/ls" ]
then 
    if [ "$vflag" = 1 ]
    then
	echo "$status: PASSED on `date`"
    fi
    exit 0
else
    echo "$error: FAILED on `date`" 
    exit 1
fi
